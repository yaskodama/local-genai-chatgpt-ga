(* gui_font.ml — compact 8x8 bitmap font for the SDL-based IDE.
   Covers printable ASCII (0x20..0x7E). Each glyph is 8 bytes; each byte is
   one row, MSB = leftmost pixel.

   This is a hand-rolled readable-but-chunky bitmap font — not meant to be
   pretty, just legible enough for source code, log lines and labels. *)

let glyph_width  = 8
let glyph_height = 8

(* Helper: pack a row of up to 8 characters (. = off, X = on) into a byte. *)
let r s =
  let n = String.length s in
  let b = ref 0 in
  for i = 0 to min 7 (n - 1) do
    if s.[i] = 'X' then b := !b lor (1 lsl (7 - i))
  done;
  !b

let blank =
  [| 0;0;0;0;0;0;0;0 |]

(* Font table indexed by char_code - 0x20. *)
let table : int array array = Array.make 96 blank

let set c rows = table.(Char.code c - 0x20) <- rows

